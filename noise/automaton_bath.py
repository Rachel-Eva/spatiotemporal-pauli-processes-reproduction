import numpy as np
import stim

class AutomatonBath:
    def __init__(self, circuit: stim.Circuit, a: float = 1e-4, b: float = 0.5, theta: float = 0.39 * np.pi, n_vector: tuple[float, float, float] = [1/np.sqrt(3), 1/np.sqrt(3), 1/np.sqrt(3)], rng= None):
        '''
        d is the Surface code distance
        a is the transition probability from calm to storm
        b is the transition probability from storm to calm
        theta is the rotational angle
        n_vector constitutes the probability of an X, Y and Z error respectively
        p_pauli is the probaility of each X, Y, Z pauli error normalized
        '''
        self.a = a
        self.b = b
        self.theta = theta
        self.rng = rng if rng is not None else np.random.default_rng()
        w = np.array([n**2 for n in n_vector], dtype=float)
        self.p_pauli = w / w.sum()

        # Get qubit positions
        coords = circuit.get_final_qubit_coordinates() # qubit's (x,y) position
        self.ids = np.array(sorted(coords)) # parse qubit id generated by Stim
        self.n_total = circuit.num_qubits
        n = self.num_qubits = len(self.ids)
        pos = {q: i for i,q in enumerate(self.ids)} # maps each real id to a compact index 0 to n−1

        data = None # red
        for ins in circuit[::-1]:
            if ins.name in ("M","MX"): # ins.name is the name of the gate 
                data = {t.value for t in ins.targets_copy()} # the specific qubit the gate is acting on
                break # checks only the final measurement applied on the data qubits
        self.red = np.array(sorted(pos[q] for q in data), dtype=np.int64)
        self.black = np.array([pos[q] for q in self.ids if q not in data], dtype=np.int64)

        # nearest neighbour
        xy_coords = np.array([coords[q] for q in self.ids], dtype= float)
        D = np.linalg.norm(xy_coords[:,None]-xy_coords[None], axis=-1)
        # filled with infinity because the diagonal represents every qubits' distance to itself
        np.fill_diagonal(D, np.inf) 
        adj = np.abs(D - D.min()) < 1e-6
        assert not adj[np.ix_(self.red, self.red)].any(), "red-red neighbors"
        assert not adj[np.ix_(self.black, self.black)].any(), "black-black neighbors"

        maxdeg = int(adj.sum(1).max())
        # a table where row i lists qubit i’s neighbours
        self.nbr = np.full((n, maxdeg), n, dtype=np.int64)
        for i in range(n): # looping number of qubits
            js = np.flatnonzero(adj[i]) # gives the list of indices which are neighbors to qubit i
            self.nbr[i, :len(js)] = js # adding the neighbors to the neighbors list

        # a lookup table of sin^2(kθ) for k excited neighbours
        self.p_flip = np.sin(np.arange(maxdeg + 1) * theta / 2) ** 2 # +1 because neighbor count starts at 0
        self.reset()

    def reset(self):
        '''
        Resets the states of the qubits to 0.
        '''
        self.s = np.zeros(self.num_qubits + 1, dtype=np.int8)

    def step(self) -> np.ndarray:
        '''
        Progresses the storm by one round by implementing the black and red half-step.
        '''
        n = self.num_qubits
        s = self.s
        rand = self.rng.random(n) # random number per site
        s[:n] = np.where(s[:n] == 0, rand < self.a, rand >= self.b)
        # runs black first, then red
        for targets in (self.black, self.red):
            k = s[self.nbr[targets]].sum(axis=1) # total number of excited neighbors
            flip = self.rng.random(len(targets)) < self.p_flip[k] # boolean array of true or false
            s[targets] ^= flip.astype(np.int8)
        paulis = self.rng.choice([1, 2, 3], size=n, p=self.p_pauli)
        out = np.zeros(self.n_total, dtype= np.int64)
        out[self.ids] = np.where(s[:n] == 1, paulis, 0)
        return out

    def estimate_marginal(self, n_steps = 20_000, burn_in = 2_000) -> float:
        '''
        Identifies what fraction of qubits has an error in a given round
        It helps calculate the average fault probability
        '''
        self.reset()
        tot = 0.0
        for t in range(n_steps + burn_in):
            self.step()
            if t >= burn_in:
                tot += self.s[:self.num_qubits].mean()
        self.reset()
        return float(tot / n_steps)